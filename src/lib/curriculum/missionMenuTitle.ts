export function missionMenuTitle(summary?: string): string | null {
  const normalized = summary?.replace(/\s+/g, " ").trim().replace(/[.。]$/, "") ?? "";
  // Future content can use its own short title; omit an unedited long description.
  return MENU_TITLES[normalized] ?? (normalized.length > 0 && normalized.length <= 20 ? normalized : null);
}
